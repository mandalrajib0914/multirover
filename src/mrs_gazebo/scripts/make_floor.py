#!/usr/bin/env python3
"""Generate the Gazebo world, the victim model and the ground-truth map from floor_plan.yaml.

  ros2 run mrs_gazebo make_floor.py                 # uses config/floor_plan.yaml
  ros2 run mrs_gazebo make_floor.py my_plan.yaml

Writes (inside the mrs_gazebo source package):
  worlds/floor.sdf, worlds/floor_novictim.sdf (victim spawned at run time, S8)
  models/victim/{model.config, model.sdf, materials/textures/aruco_<id>.png}
  maps/floor_gt.{pgm,yaml} (with the victim box), maps/floor_gt_novictim.{pgm,yaml}
"""
import argparse
import math
import os

import cv2
import numpy as np
import yaml

# Resolve through the --symlink-install symlink so outputs land in src/, not install/.
PKG_DIR = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))


def wall_box(x1, y1, x2, y2, thickness):
    """Centre, yaw and length of a wall segment. Length is extended by the thickness
    so that corners close."""
    length = math.hypot(x2 - x1, y2 - y1) + thickness
    return (x1 + x2) / 2, (y1 + y2) / 2, math.atan2(y2 - y1, x2 - x1), length


def box_link(name, x, y, z, yaw, sx, sy, sz, rgba):
    color = ' '.join(str(c) for c in rgba)
    return f"""
      <link name="{name}">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.4f}</pose>
        <collision name="collision">
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
          <material><ambient>{color}</ambient><diffuse>{color}</diffuse></material>
        </visual>
      </link>"""


def make_world(plan, with_victim=True):
    h, t = plan['wall_height'], plan['wall_thickness']
    links = []
    for i, (x1, y1, x2, y2) in enumerate(plan['walls']):
        cx, cy, yaw, length = wall_box(x1, y1, x2, y2, t)
        links.append(box_link(f'wall_{i}', cx, cy, h / 2, yaw, length, t, h, (0.75, 0.75, 0.72, 1)))
    for i, (cx, cy, sx, sy) in enumerate(plan.get('obstacles', [])):
        links.append(box_link(f'obstacle_{i}', cx, cy, h / 2, 0.0, sx, sy, h, (0.35, 0.45, 0.6, 1)))

    vx, vy, vyaw = plan['victim']
    vs = plan['aruco']['victim_size']
    victim_include = f"""    <include>
      <name>victim</name>
      <uri>model://victim</uri>
      <pose>{vx} {vy} {vs / 2} 0 0 {vyaw}</pose>
    </include>"""

    return f"""<?xml version="1.0"?>
<!-- GENERATED by make_floor.py from floor_plan.yaml. Do not edit by hand. -->
<sdf version="1.9">
  <world name="floor">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.7 0.8 0.9 1</background>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>50 50</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>50 50</size></plane></geometry>
          <material><ambient>0.5 0.5 0.5 1</ambient><diffuse>0.55 0.55 0.52 1</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="floor_walls">
      <static>true</static>{''.join(links)}
    </model>

{victim_include if with_victim else '    <!-- no victim: spawned at run time (sim_robots.launch.py, S8 trials) -->'}
  </world>
</sdf>
"""


def aruco_image(dict_name, marker_id, marker_px, border_px):
    dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, dict_name))
    if hasattr(cv2.aruco, 'generateImageMarker'):   # OpenCV >= 4.7
        marker = cv2.aruco.generateImageMarker(dictionary, marker_id, marker_px)
    else:                                            # OpenCV 4.6 (Ubuntu 24.04)
        marker = cv2.aruco.drawMarker(dictionary, marker_id, marker_px)
    return cv2.copyMakeBorder(marker, border_px, border_px, border_px, border_px,
                              cv2.BORDER_CONSTANT, value=255)


def make_victim(plan):
    a = plan['aruco']
    vs, ms = a['victim_size'], a['marker_size']
    model_dir = os.path.join(PKG_DIR, 'models', 'victim')
    tex_dir = os.path.join(model_dir, 'materials', 'textures')
    os.makedirs(tex_dir, exist_ok=True)

    # Face texture covers the whole victim face; the black marker is ms of vs.
    face_px = 512
    marker_px = int(round(face_px * ms / vs))
    img = aruco_image(a['dictionary'], a['id'], marker_px, (face_px - marker_px) // 2)
    img = cv2.resize(img, (face_px, face_px), interpolation=cv2.INTER_NEAREST)
    tex_name = f"aruco_{a['id']}.png"
    cv2.imwrite(os.path.join(tex_dir, tex_name), img)

    with open(os.path.join(model_dir, 'model.config'), 'w') as f:
        f.write("""<?xml version="1.0"?>
<model>
  <name>victim</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Victim stand-in: box with an ArUco marker on its +x face. GENERATED by make_floor.py.</description>
</model>
""")

    plate = 0.002
    with open(os.path.join(model_dir, 'model.sdf'), 'w') as f:
        f.write(f"""<?xml version="1.0"?>
<!-- GENERATED by make_floor.py from floor_plan.yaml. Do not edit by hand. -->
<sdf version="1.9">
  <model name="victim">
    <static>true</static>
    <link name="body">
      <collision name="collision">
        <geometry><box><size>{vs} {vs} {vs}</size></box></geometry>
      </collision>
      <visual name="visual">
        <geometry><box><size>{vs} {vs} {vs}</size></box></geometry>
        <material><ambient>0.8 0.1 0.1 1</ambient><diffuse>0.8 0.1 0.1 1</diffuse></material>
      </visual>
      <!-- Marker plate on the +x face; a plane's texture maps once over the whole face -->
      <visual name="aruco_face">
        <pose>{vs / 2 + plate} 0 0 0 1.5708 0</pose>
        <geometry><plane><normal>0 0 1</normal><size>{vs} {vs}</size></plane></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <pbr><metal>
            <albedo_map>materials/textures/{tex_name}</albedo_map>
            <metalness>0.0</metalness>
            <roughness>1.0</roughness>
          </metal></pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
""")


def draw_segment(grid, res, ox, oy, x1, y1, x2, y2, half_width, value):
    """Rasterise a thick segment: every cell whose centre is within half_width of it."""
    hgt, wid = grid.shape
    ys, xs = np.mgrid[0:hgt, 0:wid]
    px = ox + (xs + 0.5) * res
    py = oy + (ys + 0.5) * res
    dx, dy = x2 - x1, y2 - y1
    L2 = dx * dx + dy * dy
    u = np.clip(((px - x1) * dx + (py - y1) * dy) / L2, 0.0, 1.0) if L2 > 0 else 0.0
    d = np.hypot(px - (x1 + u * dx), py - (y1 + u * dy))
    grid[d <= half_width + 1e-6] = value


def make_gt_map(plan):
    g = plan['gt_map']
    res, margin = g['resolution'], g['margin']
    t = plan['wall_thickness']
    pts = np.array(plan['walls'], dtype=float).reshape(-1, 2)
    xmin, ymin = pts.min(axis=0)
    xmax, ymax = pts.max(axis=0)
    # Half-cell offset puts cell centres on multiples of res, so a wall on a grid line
    # is exactly one row/column of cells instead of straddling two.
    ox, oy = xmin - margin - res / 2, ymin - margin - res / 2
    wid = int(math.ceil((xmax - xmin + 2 * margin) / res)) + 1
    hgt = int(math.ceil((ymax - ymin + 2 * margin) / res)) + 1

    UNKNOWN, FREE, OCC = 205, 254, 0
    grid = np.full((hgt, wid), UNKNOWN, dtype=np.uint8)
    # Inside the arena's bounding box is free, then walls/obstacles are painted occupied.
    i0, i1 = int((xmin - ox) / res), int(math.ceil((xmax - ox) / res))
    j0, j1 = int((ymin - oy) / res), int(math.ceil((ymax - oy) / res))
    grid[j0:j1, i0:i1] = FREE
    half = max(t / 2, res / 2)
    for x1, y1, x2, y2 in plan['walls']:
        # extend by half the thickness at both ends, like the sim boxes
        L = math.hypot(x2 - x1, y2 - y1)
        ex, ey = (x2 - x1) / L * t / 2, (y2 - y1) / L * t / 2
        draw_segment(grid, res, ox, oy, x1 - ex, y1 - ey, x2 + ex, y2 + ey, half, OCC)
    for cx, cy, sx, sy in plan.get('obstacles', []):
        a0, a1 = int(round((cx - sx / 2 - ox) / res)), int(round((cx + sx / 2 - ox) / res))
        b0, b1 = int(round((cy - sy / 2 - oy) / res)), int(round((cy + sy / 2 - oy) / res))
        grid[b0:b1, a0:a1] = OCC
    maps_dir = os.path.join(PKG_DIR, 'maps')
    os.makedirs(maps_dir, exist_ok=True)

    def write(name, g):
        # PGM row 0 is the top of the map (max y)
        cv2.imwrite(os.path.join(maps_dir, f'{name}.pgm'), np.flipud(g))
        with open(os.path.join(maps_dir, f'{name}.yaml'), 'w') as f:
            f.write(f"""# GENERATED by make_floor.py from floor_plan.yaml (world frame)
image: {name}.pgm
mode: trinary
resolution: {res}
origin: [{ox:.4f}, {oy:.4f}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.196
# 0.196 < (255-205)/255, so the 205 border stays unknown (0.25 would read it as free)
""")

    # Without the victim: S8 trials move it, and map_vs_gt.py --victim draws it where it is.
    write('floor_gt_novictim', grid)
    vx, vy, _ = plan['victim']
    vs = plan['aruco']['victim_size']
    a0, a1 = int(round((vx - vs / 2 - ox) / res)), int(round((vx + vs / 2 - ox) / res))
    b0, b1 = int(round((vy - vs / 2 - oy) / res)), int(round((vy + vs / 2 - oy) / res))
    grid[b0:b1, a0:a1] = OCC
    write('floor_gt', grid)
    return wid, hgt


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('plan', nargs='?', default=os.path.join(PKG_DIR, 'config', 'floor_plan.yaml'))
    args = parser.parse_args()

    with open(args.plan) as f:
        plan = yaml.safe_load(f)

    os.makedirs(os.path.join(PKG_DIR, 'worlds'), exist_ok=True)
    with open(os.path.join(PKG_DIR, 'worlds', 'floor.sdf'), 'w') as f:
        f.write(make_world(plan))
    with open(os.path.join(PKG_DIR, 'worlds', 'floor_novictim.sdf'), 'w') as f:
        f.write(make_world(plan, with_victim=False))
    make_victim(plan)
    wid, hgt = make_gt_map(plan)
    print(f'Wrote worlds/floor.sdf, models/victim/, maps/floor_gt.pgm ({wid}x{hgt}) in {PKG_DIR}')


if __name__ == '__main__':
    main()
