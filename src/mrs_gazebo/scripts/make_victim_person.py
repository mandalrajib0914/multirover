#!/usr/bin/env python3
"""Make models/victim_person: a doll-sized seated person for the YOLO victim test (S7b).

  ros2 run mrs_gazebo make_victim_person.py [--scale 0.4] [--src <Fuel model dir>]

Source: OpenRobotics "Rescue Randy Sitting" (Gazebo Fuel, version 8, license CC0 1.0 - the
SubT challenge's victim mannequin). Get it once with
  gz fuel download -u "https://fuel.gazebosim.org/1.0/OpenRobotics/models/Rescue Randy Sitting"
The mesh is 0.73 m tall, 0.75 x 1.02 m, legs along -y. The generated model:
  * is scaled by --scale (0.4 -> 0.29 m tall, under the 0.30 m walls: at full size the
    robot camera could see the person over a wall while the lidar hit the wall, and the
    real robots' victim is a small doll)
  * faces the model's +x (rotated +90 deg), the same convention as the ArUco victim box, so
    floor_plan / trial-set victim poses and the coordinator's viewpoints work unchanged
  * has its footprint centre at the model origin, so the victim pose is the body centre
  * drops the original's SubT proximity-detector include and thermal plugin
"""
import argparse
import glob
import math
import os
import re
import shutil

import numpy as np

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FUEL = os.path.expanduser('~/.gz/fuel/fuel.gazebosim.org/openrobotics/models/rescue randy sitting')


def mesh_bounds(dae):
    """(min, max) of the mesh vertices in metres (COLLADA <unit meter=...>)."""
    t = open(dae).read()
    unit = float(re.search(r'<unit meter="([^"]*)"', t).group(1))
    pts = [np.array(m.group(1).split(), float).reshape(-1, 3) for m in
           re.finditer(r'<float_array id="[^"]*POSITION[^"]*"[^>]*>([^<]*)</float_array>', t, re.I)]
    p = np.vstack(pts) * unit
    return p.min(axis=0), p.max(axis=0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--scale', type=float, default=0.4)
    ap.add_argument('--src', default='', help='Fuel model version dir (default: newest in the cache)')
    args = ap.parse_args()
    src = args.src or sorted(glob.glob(os.path.join(FUEL, '*')), key=lambda d: int(os.path.basename(d)))[-1]
    s = args.scale

    out = os.path.join(PKG_DIR, 'models', 'victim_person')
    os.makedirs(os.path.join(out, 'meshes'), exist_ok=True)
    os.makedirs(os.path.join(out, 'materials', 'textures'), exist_ok=True)
    shutil.copy(os.path.join(src, 'meshes', 'rescue_randy.dae'), os.path.join(out, 'meshes'))
    shutil.copy(os.path.join(src, 'materials', 'textures', 'RescueRandy_Diffuse.jpg'),
                os.path.join(out, 'materials', 'textures'))

    lo, hi = mesh_bounds(os.path.join(out, 'meshes', 'rescue_randy.dae'))
    cx, cy = (lo[0] + hi[0]) / 2 * s, (lo[1] + hi[1]) / 2 * s   # footprint centre, scaled
    yaw = math.pi / 2                                             # legs (-y) -> +x
    # link pose p, yaw: world = p + R(yaw) * (s * mesh). Put the footprint centre at the
    # origin and the lowest vertex on the floor.
    px = -(math.cos(yaw) * cx - math.sin(yaw) * cy)
    py = -(math.sin(yaw) * cx + math.cos(yaw) * cy)
    pz = -lo[2] * s
    size = (hi - lo) * s

    with open(os.path.join(out, 'model.config'), 'w') as f:
        f.write(f"""<?xml version="1.0"?>
<!-- GENERATED by make_victim_person.py. Do not edit by hand. -->
<model>
  <name>victim_person</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>Ian Chen, Cole Biesemeyer (Open Robotics): original "Rescue Randy Sitting"</name></author>
  <description>Rescue Randy Sitting (Gazebo Fuel, OpenRobotics, CC0 1.0), scaled {s} ({size[2]:.2f} m tall),
    facing +x, footprint centred on the origin. Victim for the YOLO test (multirover S7b).</description>
</model>
""")
    with open(os.path.join(out, 'model.sdf'), 'w') as f:
        f.write(f"""<?xml version="1.0"?>
<!-- GENERATED by make_victim_person.py (scale {s}). Do not edit by hand. -->
<sdf version="1.9">
  <model name="victim_person">
    <static>true</static>
    <link name="body">
      <pose>{px:.4f} {py:.4f} {pz:.4f} 0 0 {yaw:.4f}</pose>
      <collision name="collision">
        <geometry><mesh><uri>meshes/rescue_randy.dae</uri><scale>{s} {s} {s}</scale></mesh></geometry>
      </collision>
      <visual name="visual">
        <geometry><mesh><uri>meshes/rescue_randy.dae</uri><scale>{s} {s} {s}</scale></mesh></geometry>
      </visual>
    </link>
  </model>
</sdf>
""")
    print(f'Wrote {out}: scale {s}, {size[0]:.2f} x {size[1]:.2f} x {size[2]:.2f} m (mesh axes), '
          f'link pose ({px:.3f}, {py:.3f}, {pz:.3f}, yaw {yaw:.3f})')


if __name__ == '__main__':
    main()
